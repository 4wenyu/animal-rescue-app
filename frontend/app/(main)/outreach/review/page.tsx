import type { ReactNode } from "react";
import Link from "next/link";

import { auth } from "@/app/api/auth/[...nextauth]/auth";
import { prisma } from "@/lib/prisma";
import { OutreachDraftReviewQueue } from "@/src/components/outreach/OutreachDraftReviewQueue";
import { AgentRunButton } from "@/src/components/outreach/AgentRunButton";
import { flushApprovedOutreach } from "@/lib/services/outreachService";

export const dynamic = "force-dynamic";

/**
 * /outreach/review — STAFF/ADMIN-only queue for the autonomous outreach
 * agent's drafts (Tier 1.7). Server component (per CLAUDE.md): RBAC is
 * enforced here, drafts are fetched server-side, and the client component
 * only renders the approve/skip controls.
 */
export default async function OutreachReviewPage(): Promise<ReactNode> {
  const session = await auth();
  const role = (session?.user as unknown as Record<string, unknown> | undefined)
    ?.role as string | undefined;

  if (!session?.user?.id || (role !== "STAFF" && role !== "ADMIN")) {
    return (
      <div className="mx-auto max-w-3xl rounded-3xl border border-slate-200 bg-white p-8 text-center shadow-sm">
        <h1 className="text-lg font-bold text-slate-900">Staff review required</h1>
        <p className="mt-2 text-sm text-slate-600">
          Only shelter STAFF/ADMIN can review autonomous outreach drafts.
        </p>
        <Link
          href="/login"
          className="mt-5 inline-flex items-center rounded-xl bg-emerald-600 px-5 py-2.5 text-sm font-semibold text-white shadow-md transition hover:bg-emerald-500"
        >
          Sign in
        </Link>
      </div>
    );
  }

  await flushApprovedOutreach();

  const drafts = await prisma.outreachDraft.findMany({
    orderBy: [{ status: "asc" }, { createdAt: "desc" }],
    take: 100,
    select: {
      draftId: true,
      status: true,
      helpAsk: true,
      subject: true,
      body: true,
      sourceNote: true,
      createdAt: true,
      reviewedAt: true,
      profile: {
        select: {
          regionLabel: true,
          user: { select: { displayName: true } },
        },
      },
    },
  });

  // Serialize Dates to strings so the data is safe to pass to a client
  // component (React server→client boundary).
  const serializedDrafts = drafts.map((d) => ({
    ...d,
    createdAt: d.createdAt.toISOString(),
    reviewedAt: d.reviewedAt ? d.reviewedAt.toISOString() : null,
  }));

  return (
    <div className="mx-auto max-w-3xl">
      <div className="mb-6 flex items-center justify-between gap-4">
        <div>
          <p className="text-xs font-semibold uppercase tracking-widest text-emerald-600">
            RescueHub · Autonomous Outreach
          </p>
          <h1 className="mt-1 text-2xl font-extrabold tracking-tight text-slate-900">
            Review queue
          </h1>
        </div>
        <AgentRunButton />
      </div>
      <p className="mb-6 text-sm leading-relaxed text-slate-600">
        Draft outreach messages generated by the autonomous agent. Nothing is
        delivered until you approve it — this queue is the human-in-the-loop
        checkpoint.
      </p>
      <OutreachDraftReviewQueue initialDrafts={serializedDrafts} />
    </div>
  );
}
